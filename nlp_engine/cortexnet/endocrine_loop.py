class ThinkingLoop:
    """
    Coordinates the HTM Predictor, Substrate, and NeuromodulatorState.
    Acts as the Endocrine Prediction Loop Architect to integrate prediction
    errors and adjust cognitive or systemic states.
    """
    def __init__(self, htm_predictor, substrate, neuromodulator_state):
        """
        Initialize the ThinkingLoop with the necessary components.
        
        Args:
            htm_predictor: An instance of an HTM predictor that provides prediction errors.
            substrate: The underlying computational or biological substrate being modulated.
            neuromodulator_state: The state manager for neuromodulators, 
                                  which has `update_from_prediction_error(pe)`.
        """
        self.htm_predictor = htm_predictor
        self.substrate = substrate
        self.neuromodulator_state = neuromodulator_state
        self.history = []

    def process_cycle(self, sensory_input):
        """
        Executes a single cycle of the prediction loop.
        
        Args:
            sensory_input: The current input data from the environment or system.
            
        Returns:
            The output/response generated by the substrate after modulation.
        """
        # 1. Feed sensory input to the HTM Predictor to get the prediction error
        # Assuming the predictor has a method to process input and yield error
        prediction = self.htm_predictor.predict(sensory_input)
        prediction_error = self.htm_predictor.calculate_error(sensory_input, prediction)
        
        # 2. Update the NeuromodulatorState using the prediction error
        # Translates prediction error (surprise/novelty/reward) into neuromodulator changes
        # e.g., Dopamine for reward prediction error, Noradrenaline for surprise.
        self.neuromodulator_state.update_from_prediction_error(prediction_error)
        
        # 3. Retrieve the updated neuromodulator levels
        current_neuro_state = getattr(self.neuromodulator_state, 'state', self.neuromodulator_state)
        
        # 4. Modulate the Substrate using the updated neuromodulator state
        # The substrate processes the input under the influence of the current endocrine state
        substrate_output = self.substrate.process(
            sensory_input=sensory_input,
            neuromodulator_state=current_neuro_state
        )
        
        # Log the cycle
        self.history.append({
            'input': sensory_input,
            'prediction_error': prediction_error,
            'neuromodulator_state': current_neuro_state,
            'output': substrate_output
        })
        
        return substrate_output

    def run(self, input_stream):
        """
        Runs the thinking loop continuously over a stream of inputs.
        
        Args:
            input_stream: An iterable providing sequential sensory inputs.
            
        Returns:
            A list of outputs from the substrate.
        """
        outputs = []
        for sensory_input in input_stream:
            output = self.process_cycle(sensory_input)
            outputs.append(output)
        return outputs
